"""Vulkan entry points of libdm.so as trampolines (dm/android/vk_tramp.S + vk_tramp_names.h), so the Vulkan driver can be
chosen at run time (vk_driver.c: the system loader or a custom driver such as Turnip through adrenotools).
Usage: python tools/gen_vk_tramp.py [names.txt]   (default work/vk_imports.txt = `llvm-nm -D --undefined-only libdm.so` vk*
symbols of a build that still links libvulkan.so; vkGetInstanceProcAddr is always included).
Each trampoline jumps through dm_vk_table[i]; an empty slot goes to dm_vk_slow (vk_driver.c resolves it, then jumps)."""
import sys
names = sorted(set(l.strip() for l in open(sys.argv[1] if len(sys.argv) > 1 else 'work/vk_imports.txt') if l.strip().startswith('vk'))
          | {'vkGetInstanceProcAddr'})
S = ['// Generated by tools/gen_vk_tramp.py: one trampoline per Vulkan entry point libdm.so calls (see vk_driver.c).',
     '    .text', '    .p2align 2']
for i, n in enumerate(names):
    S += [f'    .globl {n}', f'    .hidden {n}', f'    .type {n}, %function', f'{n}:',
          '    adrp x16, dm_vk_table', '    add x16, x16, :lo12:dm_vk_table', f'    ldr x17, [x16, #{i * 8}]',
          '    cbz x17, 1f', '    br x17', f'1:  mov x17, #{i}', '    b dm_vk_slow', f'    .size {n}, .-{n}']
# dm_vk_slow: x17 = slot. Keeps the argument registers (x0-x7, q0-q7) and x8 across the resolver, then jumps to the function.
S += ['    .globl dm_vk_slow', '    .hidden dm_vk_slow', '    .type dm_vk_slow, %function', 'dm_vk_slow:',
      '    stp x29, x30, [sp, #-224]!', '    mov x29, sp',
      '    stp x0, x1, [sp, #16]', '    stp x2, x3, [sp, #32]', '    stp x4, x5, [sp, #48]', '    stp x6, x7, [sp, #64]',
      '    str x8, [sp, #80]', '    stp q0, q1, [sp, #96]', '    stp q2, q3, [sp, #128]', '    stp q4, q5, [sp, #160]',
      '    stp q6, q7, [sp, #192]',
      '    mov x0, x17', '    bl dm_vk_resolve', '    mov x17, x0',
      '    ldp q6, q7, [sp, #192]', '    ldp q4, q5, [sp, #160]', '    ldp q2, q3, [sp, #128]', '    ldp q0, q1, [sp, #96]',
      '    ldr x8, [sp, #80]', '    ldp x6, x7, [sp, #64]', '    ldp x4, x5, [sp, #48]', '    ldp x2, x3, [sp, #32]',
      '    ldp x0, x1, [sp, #16]', '    ldp x29, x30, [sp], #224', '    br x17', '    .size dm_vk_slow, .-dm_vk_slow',
      '    .section .note.GNU-stack,"",%progbits', '']
open('dm/android/vk_tramp.S', 'w', newline='\n').write('\n'.join(S))
H = ['// Generated by tools/gen_vk_tramp.py: the Vulkan entry points behind vk_tramp.S, in slot order.',
     f'#define DM_VK_COUNT {len(names)}', 'static const char *const dm_vk_names[DM_VK_COUNT] = {']
H += [f'    "{n}",' for n in names] + ['};', '']
open('dm/android/vk_tramp_names.h', 'w', newline='\n').write('\n'.join(H))
print(len(names), 'entry points')
